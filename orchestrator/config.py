import os
from functools import lru_cache
from dotenv import load_dotenv
import logging
from langchain_openai import ChatOpenAI

load_dotenv()
logger = logging.getLogger(__name__)

@lru_cache
def get_planner_llm() -> ChatOpenAI:
    return ChatOpenAI(
        model=os.environ["PLANNER_MODEL"],
        api_key=os.getenv("PLANNER_API_KEY", os.environ["API_KEY"]),
        base_url=os.getenv("PLANNER_BASE_URL", os.environ["BASE_URL"]),
        temperature=0.1,
        timeout=300,
        max_retries=0,
    )

@lru_cache
def get_executor_llm() -> ChatOpenAI:
    return ChatOpenAI(
        model=os.environ["EXECUTOR_MODEL"],
        api_key=os.getenv("EXECUTOR_API_KEY", os.environ["API_KEY"]),
        base_url=os.getenv("EXECUTOR_BASE_URL", os.environ["BASE_URL"]),
        temperature=0.3,
        timeout=120,
        max_retries=0,
    )

@lru_cache
def get_reviewer_llm() -> ChatOpenAI:
    return ChatOpenAI(
        model=os.environ["REVIEWER_MODEL"],
        api_key=os.getenv("REVIEWER_API_KEY", os.environ["API_KEY"]),
        base_url=os.getenv("REVIEWER_BASE_URL", os.environ["BASE_URL"]),
        temperature=0.1,
        timeout=300,
        max_retries=0,
    )

